#!/usr/bin/env python3
"""Bakes the rank badge PNGs (sourceport/game/shim/assets/rank_badges, 48x48 RGBA) into
port/app/launcher_yglobby_badges.inc: premultiplied BGRA rows the launcher draws with AlphaBlend, so the
launcher needs no image decoder. Run after the PNGs change."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "sourceport/game/shim/assets/rank_badges"
OUT = ROOT / "port/app/launcher_yglobby_badges.inc"
TIERS = ["bronze", "silver", "gold", "platinum", "diamond", "challenger"]

lines = ["// Generated by tools/bake_launcher_rank_badges.py from sourceport/game/shim/assets/rank_badges. Do not edit.",
         "// SPDX-License-Identifier: GPL-2.0-or-later",
         "constexpr int kBadgeSize = 48;",
         f"constexpr int kBadgeCount = {len(TIERS)};   // " + ", ".join(TIERS),
         "static const unsigned char kBadgeBgra[kBadgeCount][kBadgeSize * kBadgeSize * 4] = {"]
for tier in TIERS:
    im = Image.open(SRC / f"{tier}.png").convert("RGBA")
    assert im.size == (48, 48), (tier, im.size)
    data = []
    for r, g, b, a in im.getdata():
        data += [b * a // 255, g * a // 255, r * a // 255, a]
    rows = [", ".join(str(v) for v in data[i:i + 48]) for i in range(0, len(data), 48)]
    lines.append("  {  // " + tier)
    lines += ["    " + row + "," for row in rows]
    lines.append("  },")
lines.append("};")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", OUT, OUT.stat().st_size, "bytes")
